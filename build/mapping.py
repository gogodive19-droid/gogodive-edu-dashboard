_COMPILED = [(re.compile(p), big, small) for p, big, small in CLASS_RULES]

_FIRST_PAREN = re.compile(r"^\((.*?)\)\s*(.*)$")


def _clean(text):
    text = text.replace("｜", "|").replace("(", "").replace(")", "")
    text = text.replace("렁스트레징", "렁스트레칭")
    return re.sub(r"\s+", " ", text).strip()


def is_excluded(raw):
    s = raw.strip()
    return any(s.startswith(p) for p in EXCLUDED_PREFIXES)


def match_venue(text):
    """문자열 안에서 강습장을 찾아 정식 이름을 돌려준다. 없으면 None."""
    for key, name in VENUE_KEYS:
        if key in text:
            return name
    return None


def match_class(text):
    """정리된 수업종류 문자열 → (대분류, 세부). 없으면 None."""
    for rx, big, small in _COMPILED:
        m = rx.match(text)
        if m:
            return big, small(m) if callable(small) else small
    return None


def parse_class_name(raw):
    """원문 수업명 → Parsed(big, small, venue).

    제외 대상이면 None. 규칙에 없으면 UnmappedClassName.
    """
    s = raw.strip()
    if is_excluded(s):
        return None
    if s in RAW_OVERRIDES:
        return RAW_OVERRIDES[s]
    m = _FIRST_PAREN.match(s)
    if not m:
        raise UnmappedClassName(raw)
    first, rest = m.group(1).strip(), m.group(2).strip()

    if first in VENUE_PREFIX:                       # 표기 2) (강습장) 수업종류
        venue, cls_text = VENUE_PREFIX[first], rest
    else:                                           # 표기 1) (수업종류) 강습장
        venue = match_venue(rest) if rest else None
        if venue is None:                           # 표기 3) 장소 없음 → 전체가 수업종류
            venue, cls_text = NO_VENUE, (first + " " + rest).strip()
        else:
            cls_text = first

    hit = match_class(_clean(cls_text))
    if hit is None:
        raise UnmappedClassName(raw)
    big, small = hit
    if small == "코칭반" and venue in DEEP_POOL_VENUES:      # 딥풀에서 연 코칭반은 따로 센다
        big = small = "딥풀 코칭반"
    return Parsed(big, small, venue)
